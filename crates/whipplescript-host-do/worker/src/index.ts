// DR-0054 Phase B: the highest `schema_migrations` version this deploy
// understands. A rolled-back worker attached to an object stamped past this
// must refuse rather than misread (or "lazily upgrade") a layout it has never
// seen. Keep in step with the version rows `do_schema.sql` inserts.
const SUPPORTED_DO_SCHEMA_VERSION = 2;

/**
 * DR-0054 Phase B: the object's durable schema is stamped with a version newer
 * than this deploy supports. Fail closed — never serve over a misread layout,
 * and never delete anything; the deploy that stamped it reads it fine.
 */
class UnsupportedSchemaVersionError extends Error {
  constructor(found: number) {
    super(
      `durable object schema is at version ${found}, but this deploy supports up to ` +
        `version ${SUPPORTED_DO_SCHEMA_VERSION}; it was written by a newer deploy. ` +
        `Serve it with a deploy that supports version ${found} — the state is ` +
        `intact, do not delete it`,
    );
    this.name = "UnsupportedSchemaVersionError";
  }
}

// Idempotent first-touch bootstrap: a fresh DO has an empty SQLite; apply the
// schema + builtin seeds exactly once (schema_migrations doubles as the marker).
function ensureSchema(sql: SqlStorage): void {
  const marker = sql
    .exec(`SELECT name FROM sqlite_master WHERE type = 'table' AND name = 'schema_migrations'`)
    .toArray();
  if (marker.length === 0) {
    sql.exec(DO_SCHEMA);
    for (const seed of BUILTIN_SEEDS) {
      sql.exec(seed);
    }
  }
  // DR-0054 Phase B downgrade guard: refuse BEFORE any lazy upgrade below
  // touches an object written by a newer deploy — the additive tail assumes a
  // layout this code knows, and running it over a newer one could corrupt it.
  const stamped = sql
    .exec(`SELECT COALESCE(MAX(version), 0) AS version FROM schema_migrations`)
    .toArray() as { version: number }[];
  const found = stamped[0]?.version ?? 0;
  if (found > SUPPORTED_DO_SCHEMA_VERSION) {
    throw new UnsupportedSchemaVersionError(found);
  }
  // Existing placement objects predate GaugeDesk's writer profile. Keep
  // additive runtime policy seeds outside the first-touch branch so a deploy
  // upgrades those objects lazily without rewriting operator-owned rows.
  sql.exec(`INSERT OR IGNORE INTO profiles
    (profile_id, name, description, enforcement_mode, allowed_capabilities, config_json)
    VALUES (
      'profile_repo_writer',
      'repo-writer',
      'Allow governed workspace reads, writes, Bashkit commands, and agent turns.',
      'enforce',
      '["agent.tell","workspace.read","workspace.write","command.run"]',
      '{}'
    )`);
  // Issue assignment (0.2.2) is additive: an object created before it has a
  // `tracker_issues` without the column, and `CREATE TABLE` in the first-touch
  // branch above never alters an existing table. Add it lazily so a deploy
  // upgrades those objects instead of failing every tracker read.
  const hasAssignedTo = sql
    .exec(`SELECT name FROM pragma_table_info('tracker_issues') WHERE name = 'assigned_to'`)
    .toArray();
  if (hasAssignedTo.length === 0) {
    sql.exec(`ALTER TABLE tracker_issues ADD COLUMN assigned_to TEXT`);
  }
  // The release count (DR-0088) is additive on the same terms. Existing items
  // start at zero rather than replaying `claim.released` out of the event log: a
  // count that begins now is still monotone, which is all a termination measure
  // needs, and a replay would reconstruct history the projection never held.
  const hasReleases = sql
    .exec(`SELECT name FROM pragma_table_info('tracker_issues') WHERE name = 'releases'`)
    .toArray();
  if (hasReleases.length === 0) {
    sql.exec(`ALTER TABLE tracker_issues ADD COLUMN releases INTEGER NOT NULL DEFAULT 0`);
  }
  // The tracker's alias/comment/evidence tables and the content-addressed
  // event-id columns (ADR-0002 phase B1) shipped after objects existed, and the
  // first-touch branch above never revisits an existing object. The production
  // store queries all of them (`do_store.rs` tracker paths), so an object
  // without them failed every such read. Add them lazily so a deploy upgrades
  // existing Durable Objects exactly as `do_schema.sql` provisions fresh ones
  // (DR-0054 Phase A).
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_aliases (
    content_id TEXT PRIMARY KEY, alias TEXT NOT NULL UNIQUE
  )`);
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_comments (
    comment_id TEXT PRIMARY KEY, issue_id TEXT NOT NULL, author TEXT,
    body TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  // Tracker-event subscriptions are additive the same way: an object created
  // before the feed has no `tracker_subscriptions`, and the first-touch branch
  // never revisits it. Without this, every subscribed poll on an existing
  // object fails its read.
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_subscriptions (
    subscriber TEXT NOT NULL, queue TEXT NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (subscriber, queue)
  )`);
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_evidence (
    evidence_id TEXT PRIMARY KEY, issue_id TEXT NOT NULL, kind TEXT, reference TEXT,
    note TEXT, added_by TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    at_cut TEXT, basis TEXT, basis_fingerprint_json TEXT
  )`);
  // DR-0086 F3: the knowledge plane's validity keys and anchors reach the
  // DO. Objects from earlier deploys gain the evidence columns lazily and
  // the anchors table on first touch; no existing row is rewritten.
  for (const [column, definition] of [
    ["at_cut", "at_cut TEXT"],
    ["basis", "basis TEXT"],
    ["basis_fingerprint_json", "basis_fingerprint_json TEXT"],
  ] as const) {
    const present = sql
      .exec(
        `SELECT name FROM pragma_table_info('tracker_evidence') WHERE name = ?`,
        column,
      )
      .toArray();
    if (present.length === 0) {
      sql.exec(`ALTER TABLE tracker_evidence ADD COLUMN ${definition}`);
    }
  }
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_anchors (
    anchor_id TEXT PRIMARY KEY, subject TEXT NOT NULL, region TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'subject', added_by TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  // DR-0086 F5: the DO's assertion projection. The counter seed is an
  // INSERT the schema gate cannot check — kept in hand-lockstep with
  // do_schema.sql and the Rust fixture, OR IGNORE so an already-seeded
  // object is untouched.
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_assertions (
    assertion_id TEXT PRIMARY KEY, title TEXT NOT NULL,
    body TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'active',
    created_by TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  sql.exec(`CREATE TABLE IF NOT EXISTS tracker_assertion_counter (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1), next_id INTEGER NOT NULL
  )`);
  sql.exec(
    `INSERT OR IGNORE INTO tracker_assertion_counter (singleton, next_id) VALUES (1, 1)`,
  );
  for (const [column, definition] of [
    ["event_id", "event_id TEXT"],
    ["parents_json", "parents_json TEXT NOT NULL DEFAULT '[]'"],
  ] as const) {
    const present = sql
      .exec(
        `SELECT name FROM pragma_table_info('tracker_events') WHERE name = ?`,
        column,
      )
      .toArray();
    if (present.length === 0) {
      sql.exec(`ALTER TABLE tracker_events ADD COLUMN ${definition}`);
    }
  }
  // Pre-upgrade rows carry NULL event_id (distinct under a SQLite unique
  // index), so the dedup index is safe to add over an existing log.
  sql.exec(
    `CREATE UNIQUE INDEX IF NOT EXISTS idx_tracker_events_id ON tracker_events(event_id)`,
  );
  // DR-0054 Phase B: `events.format_version` is additive writer-version
  // stamping — new rows record the event format their writer produced; legacy
  // NULL rows read as version 1. Existing objects gain the column lazily, and
  // no existing row is ever rewritten (the event log is canonical).
  const hasFormatVersion = sql
    .exec(`SELECT name FROM pragma_table_info('events') WHERE name = 'format_version'`)
    .toArray();
  if (hasFormatVersion.length === 0) {
    sql.exec(`ALTER TABLE events ADD COLUMN format_version INTEGER`);
  }
  // DR-0067: the event log's hash chain. DDL ONLY here — the digests are
  // computed in Rust (`whipplescript-store::event_chain`, which compiles to
  // wasm) and backfilled lazily by `do_chain_head` at first touch. A second
  // implementation in TypeScript would be two things that must agree byte for
  // byte forever, which is the drift this deliberately refuses.
  for (const column of ["prev_digest", "entry_digest"] as const) {
    const present = sql
      .exec(`SELECT name FROM pragma_table_info('events') WHERE name = ?`, column)
      .toArray();
    if (present.length === 0) {
      sql.exec(`ALTER TABLE events ADD COLUMN ${column} TEXT`);
    }
  }
  // DR-0067 §3: the writer fence. Distinct from `revision_epoch`, which is
  // program lineage — two clocks, two names.
  const hasOwnerEpoch = sql
    .exec(`SELECT name FROM pragma_table_info('instances') WHERE name = 'owner_epoch'`)
    .toArray();
  if (hasOwnerEpoch.length === 0) {
    sql.exec(`ALTER TABLE instances ADD COLUMN owner_epoch INTEGER NOT NULL DEFAULT 0`);
  }
  // DR-0077: the operator carries a revision was activated with. Additive, and
  // read on EVERY rule pass (`rule_pass.rs` builds the carry chain), so an
  // existing object without the column fails every step rather than only a
  // revision. Its default is "no carries", which is what every revision
  // recorded before this surface existed means.
  // `register_skill` writes `skills.body` and this side never declared the
  // column, so the insert failed on every object -- fresh or not. Fresh objects
  // are fixed in `do_schema.sql`; existing ones are fixed here.
  const hasSkillBody = sql
    .exec(`SELECT name FROM pragma_table_info('skills') WHERE name = 'body'`)
    .toArray();
  if (hasSkillBody.length === 0) {
    sql.exec(`ALTER TABLE skills ADD COLUMN body TEXT NOT NULL DEFAULT ''`);
  }
  // `do_insert_effect_dependency` writes `dependency_id` and `created_by_rule`
  // and this side declared neither, so EVERY dependency edge failed to insert on
  // a real object -- the same shape as `skills.body` above, and with a wider
  // blast radius: a workflow whose steps depend on one another could not record
  // the dependency at all. Fresh objects are fixed in `do_schema.sql`; existing
  // ones here. Both are plain nullable TEXT because `ADD COLUMN` cannot add a
  // primary key, and a migrated object must end up with the same layout a fresh
  // one is provisioned with.
  for (const column of ["dependency_id", "created_by_rule"] as const) {
    const present = sql
      .exec(`SELECT name FROM pragma_table_info('effect_dependencies') WHERE name = ?`, column)
      .toArray();
    if (present.length === 0) {
      sql.exec(`ALTER TABLE effect_dependencies ADD COLUMN ${column} TEXT`);
    }
  }
  // G3: which effect wrote a tracker event. Local attribution, never part of
  // the event's content id and never exported — an imported event names an
  // effect in a store this object cannot query.
  const hasTrackerEffect = sql
    .exec(`SELECT name FROM pragma_table_info('tracker_events') WHERE name = 'effect_id'`)
    .toArray();
  if (hasTrackerEffect.length === 0) {
    sql.exec(`ALTER TABLE tracker_events ADD COLUMN effect_id TEXT`);
  }
  const hasRuleCarries = sql
    .exec(
      `SELECT name FROM pragma_table_info('instance_revisions') WHERE name = 'rule_carries_json'`,
    )
    .toArray();
  if (hasRuleCarries.length === 0) {
    sql.exec(
      `ALTER TABLE instance_revisions ADD COLUMN rule_carries_json TEXT NOT NULL DEFAULT '[]'`,
    );
  }
  // Native has enforced one event per (instance, sequence) since migration
  // 0001; this side never did, so two rows could share a position and the chain
  // would be meaningless. Adding it can only fail on an object that already
  // holds such a pair, which is a real defect and must surface rather than be
  // swallowed — a log with two events at one sequence cannot be chained.
  sql.exec(
    `CREATE UNIQUE INDEX IF NOT EXISTS events_instance_sequence_idx ON events(instance_id, sequence)`,
  );
  // Message-scoped image bodies are a broker cache, not part of the admitted
  // command. Existing objects acquire this additive table lazily.
  sql.exec(`CREATE TABLE IF NOT EXISTS host_turn_images (
    instance_id TEXT NOT NULL,
    command_id TEXT NOT NULL,
    selector TEXT NOT NULL,
    media_type TEXT NOT NULL,
    data_base64 TEXT NOT NULL,
    PRIMARY KEY (instance_id, command_id, selector)
  )`);
  // Live text is a repairable operational projection. Terminal transcript and
  // receipt events remain authority; these rows only let an SSE consumer catch
  // up after a transient disconnect during the active turn.
  sql.exec(`CREATE TABLE IF NOT EXISTS host_turn_deltas (
    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
    instance_id TEXT NOT NULL,
    command_id TEXT NOT NULL,
    delta TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  sql.exec(`CREATE INDEX IF NOT EXISTS idx_host_turn_deltas
    ON host_turn_deltas(instance_id, command_id, sequence)`);
  // Interactive user commands belong to the live agent turn, not the browser.
  // They remain pending until the Rust machine snapshot records their stable
  // ids, making steering/follow-up apply-once across reconnect and eviction.
  sql.exec(`CREATE TABLE IF NOT EXISTS public_turn_commands (
    command_id TEXT PRIMARY KEY,
    turn_command_id TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('steer', 'follow_up')),
    text TEXT NOT NULL,
    images_json TEXT NOT NULL DEFAULT '[]',
    position INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK (status IN ('pending', 'applied', 'removed')),
    announced INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    applied_at TEXT
  )`);
  sql.exec(`CREATE INDEX IF NOT EXISTS idx_public_turn_commands_pending
    ON public_turn_commands(turn_command_id, kind, status, position)`);
  // Kept separate from the historical steer/follow-up table so deployments
  // whose original CHECK constraint predates manual compaction migrate safely.
  sql.exec(`CREATE TABLE IF NOT EXISTS public_compaction_commands (
    command_id TEXT PRIMARY KEY,
    turn_command_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
      CHECK (status IN ('pending', 'applied', 'removed')),
    announced INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    applied_at TEXT
  )`);
  // Correlation-only browser command binding. WhippleScript's effect state,
  // never this row, decides whether the turn is running or terminal.
  sql.exec(`CREATE TABLE IF NOT EXISTS public_turn_binding (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
    request_id TEXT NOT NULL,
    command_id TEXT NOT NULL
  )`);
  // A public session object pins exactly one release/engagement and the
  // GaugeDesk governance root authenticated by that signed release. It is the
  // session's home; no placement/Home callback participates after bootstrap.
  sql.exec(`CREATE TABLE IF NOT EXISTS public_session_metadata (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
    release_id TEXT NOT NULL,
    session_id TEXT NOT NULL,
    instance_ref TEXT NOT NULL,
    governance_signer TEXT NOT NULL,
    governance_key TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  // The session's lifecycle event log (DR-0049 §3). Phase is the fold of these
  // rows; nothing stores a phase. Append-only, and deliberately preserved by
  // teardown so the audit trail survives payload tombstoning.
  sql.exec(`CREATE TABLE IF NOT EXISTS session_lifecycle_events (
    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
    event_json TEXT NOT NULL,
    recorded_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
}

// Row objects from `sql.exec` are column-name keyed; the Rust `DoSql` contract
// wants each row as a positional array in SELECT order. Cloudflare preserves
// column order in the returned objects, so `Object.values` reconstructs it.
function rowsToPositionalJson(cursor: Iterable<Record<string, unknown>>): string {
  const rows: unknown[][] = [];
  for (const row of cursor) {
    rows.push(Object.values(row));
  }
  return JSON.stringify(rows);
}

// `state.storage.sql` as the `DoSqlBridge` the wasm core imports. Params arrive as
// a JSON array of `null | number | string` (the marshalled `SqlValue`s).
/**
 * `onActivity` receives the kernel's ephemeral live-turn observations (DR 0061).
 * Optional because most bridge users are not driving a turn; when it is absent
 * the method still exists and does nothing, so the WASM binding never has to
 * probe for it.
 */
function makeBridge(
  sql: SqlStorage,
  onActivity?: (kind: string, detail?: string) => void,
) {
  return {
    activity(kind: string, detail?: string): void {
      onActivity?.(kind, detail);
    },
    exec(query: string, paramsJson: string): number {
      const params = JSON.parse(paramsJson) as unknown[];
      const cursor = sql.exec(query, ...params);
      return cursor.rowsWritten;
    },
    query(query: string, paramsJson: string): string {
      const params = JSON.parse(paramsJson) as unknown[];
      const cursor = sql.exec(query, ...params);
      return rowsToPositionalJson(cursor);
    },
  };
}

